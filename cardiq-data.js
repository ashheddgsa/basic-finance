const VALUE_CALC = {
  calculatePointValue: function(cardId, redemptionMethod, points) {
    const card = CARD_DB.find(c => c.id === cardId);
    if (!card) return null;
    const vpp = card.valuePerPoint;
    const methods = [];
    if (vpp.airlineTransfer) methods.push({method:"Airline Transfer (Business Class)",vpp:vpp.airlineTransfer,totalValue:points*vpp.airlineTransfer,recommended:vpp.airlineTransfer >= 1.5});
    if (vpp.smartbuy) methods.push({method:"SmartBuy Flights/Hotels",vpp:vpp.smartbuy,totalValue:points*vpp.smartbuy,recommended:true});
    if (vpp.cashback) methods.push({method:"Direct Cashback",vpp:vpp.cashback,totalValue:points*vpp.cashback,recommended:true});
    if (vpp.statement) methods.push({method:"Statement Credit",vpp:vpp.statement,totalValue:points*vpp.statement,recommended:false});
    if (vpp.vouchers) methods.push({method:"Gift Vouchers",vpp:vpp.vouchers,totalValue:points*vpp.vouchers,recommended:false});
    return methods.sort((a,b) => b.vpp - a.vpp);
  },
  getBestRedemption: function(cardId) {
    const card = CARD_DB.find(c => c.id === cardId);
    if (!card) return null;
    const vpp = card.valuePerPoint;
    const best = Object.entries(vpp).sort((a,b) => b[1]-a[1])[0];
    return {method: best[0], vpp: best[1], recommendation: card.redeem};
  }
};
